// Generates M3 color role tokens (2025 / Expressive spec) from the brand seed color.
// Run: pnpm --filter @freezer/web generate-theme  → src/theme/colors.gen.css
import {
  argbFromHex,
  Hct,
  hexFromArgb,
  MaterialDynamicColors,
  SchemeTonalSpot,
} from "@material/material-color-utilities";
import { writeFileSync } from "node:fs";

const SEED = "#35A9B5";

function roles(isDark: boolean): string {
  const scheme = new SchemeTonalSpot(Hct.fromInt(argbFromHex(SEED)), isDark, 0, "2025");
  return new MaterialDynamicColors().allColors
    .map((color) => {
      const name = color.name.replace(/_/g, "-");
      return `  --md-sys-color-${name}: ${hexFromArgb(color.getArgb(scheme))};`;
    })
    .join("\n");
}

const css = `/* @generated by scripts/generate-theme.ts from seed ${SEED} (SchemeTonalSpot, spec 2025). Do not edit. */
:root {
  color-scheme: light;
${roles(false)}
}

@media (prefers-color-scheme: dark) {
  :root {
    color-scheme: dark;
${roles(true)
  .split("\n")
  .map((l) => "  " + l)
  .join("\n")}
  }
}
`;

writeFileSync(new URL("../src/theme/colors.gen.css", import.meta.url), css);
console.log("Wrote src/theme/colors.gen.css");
