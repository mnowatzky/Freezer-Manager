import tailwindcss from "@tailwindcss/vite";
import react from "@vitejs/plugin-react";
import { defineConfig } from "vite";
import { VitePWA } from "vite-plugin-pwa";

export default defineConfig({
  envDir: "../..",
  plugins: [
    react(),
    tailwindcss(),
    VitePWA({
      registerType: "autoUpdate",
      manifest: {
        name: "Freezer Manager",
        short_name: "Freezer",
        // One manifest for all users, so it is in English (the UI itself follows the browser language).
        description: "What's frozen in which drawer?",
        lang: "en",
        // No theme_color on purpose: Chrome paints an installed app's navigation bar with it, and a
        // manifest can't have a dark variant (white bar in dark mode). Without it the bar follows the
        // system theme; the status bar uses the light/dark <meta name="theme-color"> in index.html.
        // `undefined` overrides vite-plugin-pwa's default; its "theme_color is missing" warning is outdated.
        theme_color: undefined,
        // Android 15+ draws the app window background (= background_color) behind the transparent
        // navigation bar of an installed app. Like theme_color it has no dark variant; we use the
        // dark surface so the bar matches in dark mode (light mode then gets a dark bar).
        background_color: "#0a0f10",
        display: "standalone",
        start_url: "/",
        scope: "/",
        // Open in-scope links (e.g. scanned container QR codes, /c/<n>) in the installed app instead of a
        // browser tab, and reuse the running window: main.tsx routes to the launch URL via launchQueue.
        handle_links: "preferred",
        launch_handler: { client_mode: ["focus-existing", "auto"] },
        // Generated by `pnpm generate-icons` (scripts/generate-icons.ts).
        icons: [
          { src: "/pwa-64x64.png", sizes: "64x64", type: "image/png", purpose: "any" },
          { src: "/pwa-192x192.png", sizes: "192x192", type: "image/png", purpose: "any" },
          { src: "/pwa-512x512.png", sizes: "512x512", type: "image/png", purpose: "any" },
          { src: "/maskable-icon-512x512.png", sizes: "512x512", type: "image/png", purpose: "maskable" },
          { src: "/monochrome-icon-512x512.png", sizes: "512x512", type: "image/png", purpose: "monochrome" },
        ],
      },
      workbox: {
        // App shell offline; API, auth callbacks and data are never served from the SW.
        navigateFallback: "/index.html",
        navigateFallbackDenylist: [/^\/api\//],
        // Fonts: only the Latin subsets of Google Sans Flex plus the icon font (other scripts load on demand).
        globPatterns: ["**/*.{js,css,html,svg,png,ico,wasm}", "assets/google-sans-flex-latin*.woff2", "assets/material-symbols-rounded*.woff2"],
        maximumFileSizeToCacheInBytes: 5 * 1024 * 1024,
      },
      // Serve the manifest + a dev service worker in `pnpm dev` too, so installing from the dev server
      // (e.g. via Tailscale on a phone) gets the real icons, colors and standalone mode.
      devOptions: { enabled: true, type: "module", navigateFallback: "index.html" },
    }),
  ],
  build: {
    // Never inline fonts as data: URIs; the production CSP only allows fonts from 'self'.
    assetsInlineLimit: (file) => (file.endsWith(".woff2") ? false : undefined),
  },
  server: {
    host: true, // listen on 0.0.0.0 so phones on the LAN can reach the dev server
    // Allow access via `tailscale serve` (https://<mac>.<tailnet>.ts.net), see README → Testing on a phone.
    allowedHosts: [".ts.net"],
    port: Number(process.env.WEB_PORT ?? 5173),
    strictPort: true,
    proxy: { "/api": `http://localhost:${process.env.API_PORT ?? 3000}` },
  },
});
